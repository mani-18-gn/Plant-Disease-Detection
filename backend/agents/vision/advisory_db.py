def get_diagnosis_advisory(class_index: Optional[int] = None, raw_label: Optional[str] = None) -> Dict[str, Any]:
    """
    Retrieve comprehensive agronomic metadata, differential diagnosis, and advisory guidance
    for a class index or raw label string.
    """
    if class_index is not None and class_index in CLASS_METADATA:
        return CLASS_METADATA[class_index]

    if raw_label:
        lower_lbl = raw_label.lower().strip()
        lower_key = lower_lbl.replace(" ", "_").replace("-", "_")

        # 1. Extended regional crops (Arecanut, Rice, Wheat, Cotton, etc.)
        for key, val in EXTENDED_CROP_ADVISORY.items():
            if key == lower_key or key in lower_key or val["condition"].lower() in lower_lbl:
                return val

        # 2. 38 Multi-crop PlantVillage metadata
        for item in CLASS_METADATA.values():
            formatted = f"{item['crop']} - {item['condition']}".lower()
            if (
                item["raw_label"].lower() == lower_lbl
                or item["raw_label"].lower().replace(" ", "_") == lower_key
                or formatted == lower_lbl
                or item["condition"].lower() == lower_lbl
            ):
                return item

        # 3. Partial fallback search across conditions
        for item in CLASS_METADATA.values():
            if item["condition"].lower() in lower_lbl:
                return item

    return INCONCLUSIVE_ADVICE


def search_knowledge_base(query: Optional[str] = None, crop: Optional[str] = None, lang: str = "en") -> List[Dict[str, Any]]:
    """
    Search and filter verified knowledge base across both 38-class vision models and extended Indian crops.
    """
    all_entries = list(CLASS_METADATA.values()) + list(EXTENDED_CROP_ADVISORY.values())
    results = []

    q_lower = query.lower().strip() if query else None
    crop_lower = crop.lower().strip() if crop else None

    for entry in all_entries:
        if crop_lower:
            entry_crop = entry["crop"].lower()
            entry_crop_kn = (entry.get("crop_kn") or "").lower()
            if crop_lower not in entry_crop and crop_lower not in entry_crop_kn:
                continue

        if q_lower:
            searchable_text = " ".join([
                entry["crop"],
                entry.get("crop_kn", ""),
                entry["condition"],
                entry.get("condition_kn", ""),
                entry.get("causal_agent") or "",
                entry.get("symptoms", ""),
                entry.get("differential_diagnosis", ""),
                entry.get("chemical_management", ""),
            ]).lower()
            if q_lower not in searchable_text:
                continue

        results.append(entry)

    return results


def get_all_supported_crops() -> List[Dict[str, Any]]:
    """
    Returns unique supported crops and their disease counts across vision models and extended advisories.
    """
    crop_map: Dict[str, Dict[str, Any]] = {}

    for entry in list(CLASS_METADATA.values()) + list(EXTENDED_CROP_ADVISORY.values()):
        c = entry["crop"]
        if c not in crop_map:
            crop_map[c] = {
                "crop": c,
                "crop_kn": entry.get("crop_kn"),
                "scientific_name": entry.get("scientific_name"),
                "conditions_count": 0,
                "conditions": []
            }
        crop_map[c]["conditions_count"] += 1
        crop_map[c]["conditions"].append({
            "condition": entry["condition"],
            "condition_kn": entry.get("condition_kn"),
            "is_healthy": entry.get("is_healthy", False),
            "causal_agent": entry.get("causal_agent"),
        })

    return sorted(list(crop_map.values()), key=lambda x: x["crop"])
